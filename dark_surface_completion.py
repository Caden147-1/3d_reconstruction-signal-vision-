#!/usr/bin/env python3
"""Infer a separate mesh layer for dark, weak-texture surface gaps.

Dark or nearly black surfaces often reconstruct sparsely because image matching
has weak texture. This script does not modify the raw point cloud. It estimates
a dominant dark horizontal support band from surviving colored points and writes
an inspection mesh that can be loaded next to the filtered COLMAP cloud.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

from ply_io import color_indices, read_ply_vertices, row_xyz, xyz_indices


Point2 = Tuple[float, float]
Point3 = Tuple[float, float, float]


def percentile(values: Sequence[float], ratio: float) -> float:
    if not values:
        return math.nan
    ordered = sorted(values)
    ratio = max(0.0, min(1.0, ratio))
    pos = ratio * (len(ordered) - 1)
    lo = int(math.floor(pos))
    hi = int(math.ceil(pos))
    if lo == hi:
        return ordered[lo]
    weight = pos - lo
    return ordered[lo] * (1.0 - weight) + ordered[hi] * weight


def convex_hull(points: Sequence[Point2]) -> List[Point2]:
    unique = sorted(set(points))
    if len(unique) <= 1:
        return list(unique)

    def cross(origin: Point2, a: Point2, b: Point2) -> float:
        return (a[0] - origin[0]) * (b[1] - origin[1]) - (a[1] - origin[1]) * (b[0] - origin[0])

    lower: List[Point2] = []
    for point in unique:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], point) <= 0:
            lower.pop()
        lower.append(point)

    upper: List[Point2] = []
    for point in reversed(unique):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], point) <= 0:
            upper.pop()
        upper.append(point)

    return lower[:-1] + upper[:-1]


def polygon_area(points: Sequence[Point2]) -> float:
    if len(points) < 3:
        return 0.0
    total = 0.0
    for idx, point in enumerate(points):
        nxt = points[(idx + 1) % len(points)]
        total += point[0] * nxt[1] - nxt[0] * point[1]
    return abs(total) * 0.5


def expand_polygon(points: Sequence[Point2], padding: float) -> List[Point2]:
    if not points or padding <= 0:
        return list(points)
    cx = sum(point[0] for point in points) / len(points)
    cy = sum(point[1] for point in points) / len(points)
    expanded: List[Point2] = []
    for x, y in points:
        dx = x - cx
        dy = y - cy
        length = math.hypot(dx, dy)
        if length <= 1e-9:
            expanded.append((x, y))
        else:
            scale = (length + padding) / length
            expanded.append((cx + dx * scale, cy + dy * scale))
    return expanded


def choose_vertical_axis(points: Sequence[Point3]) -> int:
    ranges = []
    for axis in range(3):
        values = [point[axis] for point in points]
        ranges.append(max(values) - min(values))
    return min(range(3), key=lambda axis: ranges[axis])


def luminance(row: Sequence[Any], color: Tuple[int, int, int]) -> float:
    r = float(row[color[0]])
    g = float(row[color[1]])
    b = float(row[color[2]])
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def trim_projected(points: Sequence[Point2]) -> List[Point2]:
    if len(points) < 12:
        return list(points)
    xs = [point[0] for point in points]
    ys = [point[1] for point in points]
    min_x, max_x = percentile(xs, 0.02), percentile(xs, 0.98)
    min_y, max_y = percentile(ys, 0.02), percentile(ys, 0.98)
    return [
        point
        for point in points
        if min_x <= point[0] <= max_x and min_y <= point[1] <= max_y
    ]


def build_mesh_vertices(hull: Sequence[Point2], vertical_axis: int, height: float) -> List[Point3]:
    axes = [axis for axis in range(3) if axis != vertical_axis]
    vertices: List[Point3] = []
    for u, v in hull:
        coords = [0.0, 0.0, 0.0]
        coords[vertical_axis] = height
        coords[axes[0]] = u
        coords[axes[1]] = v
        vertices.append((coords[0], coords[1], coords[2]))
    return vertices


def write_dark_mesh(path: Path, vertices: Sequence[Point3]) -> None:
    if len(vertices) < 3:
        raise ValueError("Need at least three vertices to write a dark surface mesh")
    path.parent.mkdir(parents=True, exist_ok=True)
    faces = [(0, index, index + 1) for index in range(1, len(vertices) - 1)]
    lines = [
        "ply",
        "format ascii 1.0",
        "comment generated by dark_surface_completion.py",
        f"element vertex {len(vertices)}",
        "property float x",
        "property float y",
        "property float z",
        "property uchar red",
        "property uchar green",
        "property uchar blue",
        f"element face {len(faces)}",
        "property list uchar int vertex_indices",
        "end_header",
    ]
    for x, y, z in vertices:
        lines.append(f"{x:.6f} {y:.6f} {z:.6f} 18 18 18")
    for a, b, c in faces:
        lines.append(f"3 {a} {b} {c}")
    path.write_text("\n".join(lines) + "\n", encoding="ascii")


def select_candidate(
    dark_points: Sequence[Point3],
    vertical_axis: int,
    min_support: int,
    thickness_ratio: float,
    bin_count: int,
) -> Dict[str, Any]:
    values = [point[vertical_axis] for point in dark_points]
    min_value, max_value = min(values), max(values)
    span = max(max_value - min_value, 1e-9)
    thickness = max(span * thickness_ratio, 0.02)
    bin_count = max(4, min(bin_count, max(4, int(math.sqrt(len(dark_points))))))
    bin_width = span / bin_count
    buckets: List[List[Point3]] = [[] for _ in range(bin_count)]
    for point in dark_points:
        bucket = min(bin_count - 1, int((point[vertical_axis] - min_value) / max(bin_width, 1e-9)))
        buckets[bucket].append(point)

    axes = [axis for axis in range(3) if axis != vertical_axis]
    candidates: List[Dict[str, Any]] = []
    for bucket in buckets:
        if len(bucket) < min_support:
            continue
        height = percentile([point[vertical_axis] for point in bucket], 0.5)
        support = [
            point
            for point in dark_points
            if abs(point[vertical_axis] - height) <= thickness
        ]
        if len(support) < min_support:
            continue
        projected = trim_projected([(point[axes[0]], point[axes[1]]) for point in support])
        hull = convex_hull(projected)
        area = polygon_area(hull)
        if len(hull) < 3 or area <= 0:
            continue
        candidates.append(
            {
                "height": height,
                "thickness": thickness,
                "support_count": len(support),
                "hull": hull,
                "hull_area": area,
                "score": area * math.log(len(support) + 1),
            }
        )

    if not candidates:
        raise ValueError("No dominant dark surface support band was found")
    return max(candidates, key=lambda item: (item["score"], item["support_count"]))


def complete_dark_surface(
    input_path: Path,
    output_path: Path,
    summary_path: Optional[Path],
    dark_threshold: float,
    max_points: int,
    min_support: int,
    thickness_ratio: float,
    hull_padding: float,
    min_hull_area: float,
    bin_count: int,
) -> Dict[str, Any]:
    properties, rows, io_summary = read_ply_vertices(input_path, max_vertices=max_points)
    xyz = xyz_indices(properties)
    color = color_indices(properties)
    if color is None:
        raise ValueError("PLY vertices do not include RGB color properties")

    all_points = [row_xyz(row, xyz) for row in rows]
    dark_points = [
        point
        for row, point in zip(rows, all_points)
        if luminance(row, color) <= dark_threshold
    ]
    if len(dark_points) < min_support:
        raise ValueError(f"Only {len(dark_points)} dark points found; need at least {min_support}")

    stride = int(io_summary.get("sample_stride") or 1)
    sampled_dark_points = dark_points
    vertical_axis = choose_vertical_axis(all_points)
    chosen = select_candidate(
        sampled_dark_points,
        vertical_axis=vertical_axis,
        min_support=min(min_support, len(sampled_dark_points)),
        thickness_ratio=thickness_ratio,
        bin_count=bin_count,
    )
    if chosen["hull_area"] < min_hull_area:
        raise ValueError(
            f"Dark surface hull area {chosen['hull_area']:.6f} is below minimum {min_hull_area:.6f}"
        )

    hull = expand_polygon(chosen["hull"], hull_padding)
    vertices = build_mesh_vertices(hull, vertical_axis, chosen["height"])
    write_dark_mesh(output_path, vertices)

    summary = {
        "status": "ok",
        "input": str(input_path.resolve()),
        "output": str(output_path.resolve()),
        "method": "dominant_dark_horizontal_support_band_convex_hull",
        "dark_threshold": dark_threshold,
        "input_vertex_count": len(rows),
        "dark_point_count": len(dark_points),
        "sample_stride": stride,
        "sampled_dark_point_count": len(sampled_dark_points),
        "vertical_axis": ["x", "y", "z"][vertical_axis],
        "surface_height": round(chosen["height"], 6),
        "support_thickness": round(chosen["thickness"], 6),
        "support_count": chosen["support_count"],
        "hull_vertex_count": len(hull),
        "hull_area": round(polygon_area(hull), 6),
        "hull_padding": hull_padding,
        **io_summary,
        "explanation": (
            "A dark-color point subset is used to infer one dominant low-texture "
            "surface. The result is an inspection mesh layer, not a replacement "
            "for the raw COLMAP reconstruction."
        ),
    }
    if summary_path:
        summary_path.parent.mkdir(parents=True, exist_ok=True)
        summary_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return summary


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--summary", type=Path)
    parser.add_argument("--dark-threshold", type=float, default=55.0)
    parser.add_argument("--max-points", type=int, default=250000)
    parser.add_argument("--min-support", type=int, default=80)
    parser.add_argument("--thickness-ratio", type=float, default=0.025)
    parser.add_argument("--hull-padding", type=float, default=0.05)
    parser.add_argument("--min-hull-area", type=float, default=0.02)
    parser.add_argument("--bin-count", type=int, default=48)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    summary = complete_dark_surface(
        input_path=args.input,
        output_path=args.output,
        summary_path=args.summary,
        dark_threshold=args.dark_threshold,
        max_points=args.max_points,
        min_support=args.min_support,
        thickness_ratio=args.thickness_ratio,
        hull_padding=args.hull_padding,
        min_hull_area=args.min_hull_area,
        bin_count=args.bin_count,
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
